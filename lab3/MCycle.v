module MCycle #(
    parameter width = 32
)  // Keep this at 4 to verify your algorithms with 4 bit numbers (easier). When using MCycle as a component in RV, generic map it to 32.
(
    input CLK,
    input RESET,
    input Start,                     // Multi-cycle Enable. The control unit should assert this when an instruction with a multi-cycle operation is detected.
    input [1:0] MCycleOp,            // 00 signed multiplication, 01 unsigned multiplication, 10 signed division, 11 unsigned division. Generated by Control unit
    input [width-1:0] Operand1,  // Multiplicand / Dividend
    input [width-1:0] Operand2,  // Multiplier / Divisor
    output reg [width-1:0] Result1,  // LSW of Product / Quotient
    output reg [width-1:0] Result2,  // MSW of Product / Remainder
    output reg Busy                  // Set immediately when Start is set. Cleared when the Results become ready. This bit can be used to stall the processor while multi-cycle operations are on.
);

    // since the IDLE_PROCESS is combinational, instantaneously asserts Busy once Start is asserted
    localparam IDLE = 1'b0;
    localparam COMPUTING = 1'b1;

    // Last value of count for each multiplication. Part-selected where they are
    // used, so the comparisons against count do not silently widen it.
    localparam COUNT_LAST_W = width - 1;  // unsigned multiply, W bits
    localparam COUNT_LAST_2W = 2 * width - 1;  // signed multiply, sign extended to 2W bits

    reg state = IDLE;
    reg n_state = IDLE;

    reg done = 1'b0;
    reg [7:0] count = 0;  // assuming no computation takes more than 256 cycles.
    reg [2*width-1:0] temp_sum = 0;
    reg [2*width-1:0] shifted_op1 = 0;
    reg [2*width-1:0] shifted_op2 = 0;

    reg [2*width+1 : 0] booth = 0;
    reg [2*width+1 : 0] n_booth;

    // What each of the above becomes at the next edge. The computation is
    // written as a sequence of steps over these, so that the registers
    // themselves are only ever assigned with <= , in one place.
    reg [7:0] n_count;
    reg n_done;
    reg [2*width-1:0] n_temp_sum;
    reg [2*width-1:0] n_shifted_op1;
    reg [2*width-1:0] n_shifted_op2;
    reg [width-1:0] n_Result1;
    reg [width-1:0] n_Result2;

    always @(*) begin : IDLE_PROCESS
        // default outputs
        Busy = 1'b0;
        n_state = IDLE;

        // if reset, skip this block and stick with defaults
        if (~RESET)
            case (state)
                IDLE: begin
                    if(Start) begin // note: a mealy machine, since output depends on current state (IDLE) & input (Start)
                        n_state = COMPUTING;
                        Busy = 1'b1;
                    end
                end

                COMPUTING: begin
                    if (~done) begin
                        n_state = COMPUTING;
                        Busy = 1'b1;
                    end
                end
            endcase
    end


    always @(*) begin : COMPUTING_PROCESS  // process which does the actual computation
        // Hold, unless something below says otherwise.
        n_count = count;
        n_temp_sum = temp_sum;
        n_shifted_op1 = shifted_op1;
        n_shifted_op2 = shifted_op2;
        n_Result1 = Result1;
        n_Result2 = Result2;
        n_done = 1'b0;
        n_booth = booth;

        // n_state == COMPUTING and state == IDLE implies we are just transitioning into COMPUTING
        if( RESET | (n_state == COMPUTING & state == IDLE) ) begin // 2nd condition is true during the very 1st clock cycle of the multiplication
            n_count = 0;
            n_temp_sum = 0;

            // initialise for multiplication (booth)
            if (~MCycleOp[1]) begin
                n_shifted_op1[width : 0] = {
                    Operand1[width-1], Operand1
                };  // sign extend M (Multiplicand)

                // A                = n_booth[2*width+1: width+1] sign extend
                // Q (Multiplier)   = n_booth[width : 1] no sign extend
                // q0               = n_booth[0]
                n_booth = 0;
                n_booth[width : 1] = Operand2;
            end

            // initialise for division
            else begin
                n_Result1 = 0;
                n_shifted_op1 = {{width{1'b0}}, Operand1};
                n_shifted_op2 = {{width{1'b0}}, Operand2};
                // flip to +ve if the operand is -ve
                if (~MCycleOp[0] & Operand1[width-1]) begin
                    n_shifted_op1[width-1 : 0] = ~n_shifted_op1[width-1 : 0] + 1'b1;
                end
                if (~MCycleOp[0] & Operand2[width-1]) begin
                    n_shifted_op2[width-1 : 0] = ~n_shifted_op2[width-1 : 0] + 1'b1;
                end
            end
        end


        // Guarded so that the cycle in which Busy falls - the one the processor uses to write the result back - does not run another iteration over it, and so that the results are held while idle.
        if (n_state == COMPUTING) begin

            // MULTIPLY - BOOTHS ALGO
            if (~MCycleOp[1]) begin
                // legend :
                // M (Multiplicand) = n_shifted_op1[width : 0] sign extend
                // A                = n_booth[2*width+1: width+1] sign extend
                // Q (Multiplier)   = n_booth[width : 1] no sign extend
                // q0               = n_booth[0]
                // n                = n_count

                // step 1: 3 paths of q1q0
                case (n_booth[1 : 0])
                    2'b00, 2'b11: begin
                    end  // no op
                    2'b01:
                    n_booth[2*width+1: width+1] = n_booth[2*width+1: width+1] + n_shifted_op1[width : 0]; // A = A + M
                    2'b10:
                    n_booth[2*width+1: width+1] = n_booth[2*width+1: width+1] - n_shifted_op1[width : 0]; // A = A - M
                endcase

                // step 2: perform sra on A, Q, q0
                n_booth = {n_booth[2*width+1], n_booth[2*width+1:1]};

                // step 3: check if termination criteria hit, else increment n_count
                if (n_count == COUNT_LAST_W) begin
                    n_done = 1'b1;
                    n_Result1 = n_booth[width:1];  // LSW product
                    n_Result2 = n_booth[2*width:width+1];  // MSW product
                end
                else n_count = n_count + 1;
            end



            // DIVIDE
            else begin

                // ALGO:
                // toothpaste working dividend from unused dividend
                // (subtract) working dividend - divisor = working remainder
                // if working remainder < 0 : quotient append 0
                // if working remainder >= 0 : quotient append 1
                //      and this working remainder will be next working dividend
                // check terminate

                // LEGEND:
                // n_shifted_op1[2*width-1 : width] = working dividend
                // n_shifted_op1[width-1 : 0]       = unused dividend
                // n_shifted_op2[width-1 :0]        = divisor
                // n_temp_sum[width : 0]            = working remainder (width+1 bits long so u can pad and subtract properly)
                // n_Result1                        = quotient
                // n_Result2                        = remainder


                // push out new digit into working dividend (like toothpaste)
                // MSB is now the prev [2*width-2], pad LSB with zero
                n_shifted_op1 = {n_shifted_op1[2*width-2 : 0], 1'b0};

                // (subtract) working remainder = working dividend - divisor
                // subtract using width+1 wide registers so that the carry/overflow stuff is handled properly idk
                n_temp_sum[width :0] = {1'b0, n_shifted_op1[2*width-1 :width]} - {1'b0, n_shifted_op2[width-1 :0]};

                // if remainder is -ve
                // ie if MSB is 1
                if (n_temp_sum[width] == 1) begin
                    n_Result1 = {n_Result1[width-2 : 0], 1'b0};  // append 0 to quotient
                end

                // if remainder >= 0
                // is if MSB is 0
                else begin
                    n_Result1 = {n_Result1[width-2 : 0], 1'b1};  // append 1 to quotient

                    // working remainder is now the next working dividend
                    // use n_temp_sum[width-1 : 0] here cos the working remainder is now 
                    n_shifted_op1[2*width-1 : width] = n_temp_sum[width-1 : 0];
                end

                // termination criteria
                if (n_count == COUNT_LAST_W[7 : 0]) begin
                    n_done = 1'b1;
                    n_Result2 = n_shifted_op1[2*width-1:width];

                    // if we doing signed div, and if operand signs are diff
                    // make quotient negative 
                    if (~MCycleOp[0] & (Operand1[width-1] ^ Operand2[width-1])) begin
                        n_Result1 = ~n_Result1 + 1;
                    end

                    // make remainder negative if Op1 (dividend) sign bit = 1
                    if (~MCycleOp[0] & Operand1[width-1]) n_Result2 = ~n_Result2 + 1;
                end

                else n_count = n_count + 1;
            end
        end
    end


    always @(posedge CLK) begin : STATE_UPDATE_PROCESS  // the only place any of this is registered
        state <= n_state;
        count <= n_count;
        done <= n_done;
        temp_sum <= n_temp_sum;
        shifted_op1 <= n_shifted_op1;
        shifted_op2 <= n_shifted_op2;
        Result1 <= n_Result1;
        Result2 <= n_Result2;
        booth <= n_booth;
    end

endmodule
