module RV #(
    parameter PC_INIT = 32'h00400000
) (
    input CLK,
    input RESET,
    //input Interrupt,      // for optional future use.
    input [31:0] Instr,
    input [31:0] ReadData_in,  // Name mangled to support lb/lbu/lh/lhu
    output MemRead,
    output [3:0] MemWrite_out,  // Column-wise write enable to support sb/sw. Each column is a byte.
    output [31:0] PCF,
    output [31:0] ALUResult,
    output [31:0] WriteData_out  // Name mangled to support sb/sw
);

    // Please read Lab 4 Enhancement: Implementing additional instructions on how to support lb/lbu/lh/lhu/sb/sh

    //RV Signals
    wire [ 2:0] SizeSel;  //to support lb/lbu/lh/lhu/sb/sh
    wire [31:0] WriteData;

    // RegFile signals
    wire        WE;
    wire [31:0] WD;
    wire [31:0] ResultW;


    assign WE = RegWriteW && !RESET; // regfile doesnt stall even if we_pc = 0. cos regfile writes on posedge & we=1
    assign ALUResult = ALUResultM;

    reg [31:0] MCycle_res;
    wire MemtoReg;


    // Extend Module signals
    wire [ 2:0] ImmSrc;
    wire [24:0] InstrImm;
    wire [31:0] ExtImm;


    // ALU signals
    reg  [31:0] Src_A;
    reg  [31:0] Src_B;


    assign MemRead = MemtoRegM; // This is needed for the proper functionality of some devices such as UART CONSOLE
    assign ReadDataM = ReadData_in;  // Change datapath as appropriate if supporting lb/lbu/lh/lhu
    assign WriteData_out = WriteData;  // Change datapath as appropriate if supporting sb/sh
    assign MemWrite_out = {4{MemWriteM}};  // Change datapath as appropriate if supporting sb/sh
    assign SizeSel = 3'b010;             // Change this to be generated by the Decoder (control) as appropriate if 

    wire StallD;
    wire FlushD;
    wire [31:0] InstrF;
    wire [31:0] InstrD;
    wire [31:0] PCD;
    assign InstrF = Instr;

    DRegister DRegister1 (
        CLK,
        !StallD,
        FlushD,
        InstrF,
        PCF,
        PCD,
        InstrD
    );

    wire [31:0] RD1D, RD2D;
    wire FlushE;
    wire StallE;
    wire [2:0] func3D;
    wire [1:0] PCSD;
    wire RegWriteD;
    wire MemtoRegD;
    wire MemWriteD;
    wire [3:0] ALUControlD;
    wire [1:0] ALUSrcAD;
    wire [1:0] ALUSrcBD;
    wire [31:0] RD1D_P;
    wire [31:0] RD2D_P;
    wire [31:0] ExtImmD;
    wire [4:0] rdD;
    wire [31:0] PCE;

    assign RD1D_P = Forward1D? ResultW: RD1D;
    assign RD2D_P = Forward2D? ResultW: RD2D;

    ERegister ERegister1 (
        CLK,
        FlushE,
        StallE,
        func3D,
        PCSD,
        RegWriteD,
        MemtoRegD,
        MemWriteD,
        ALUControlD,
        ALUSrcAD,
        ALUSrcBD,
        RD1D_P,
        RD2D_P,
        ExtImmD,
        rdD,
        PCD,
        func3E,
        PCSE,
        RegWriteE,
        MemtoRegE,
        MemWriteE,
        ALUControlE,
        ALUSrcAE,
        ALUSrcBE,
        RD1E,
        RD2E,
        ExtImmE,
        rdE,
        PCE
    );

    wire [2:0] func3E;
    wire [1:0] PCSE;
    wire RegWriteE;
    wire MemtoRegE;
    wire MemWriteE;
    wire [3:0] ALUControlE;
    wire [1:0] ALUSrcAE;
    wire [1:0] ALUSrcBE;
    wire [31:0] RD1E;
    wire [31:0] RD2E;
    wire [31:0] ExtImmE;
    wire [4:0] rdE;
    wire [31:0] ALUResultE;
    wire [31:0] WriteDataE;

    reg [31:0] SrcA_tmp, SrcB_tmp;

    // ALU signals
    always @(*) begin
        Src_A = RD1E;
        Src_B = RD2E;
        SrcA_tmp = RD1E;
        SrcB_tmp = RD2E;


        //ForwardAE RD1
        case (ForwardAE)
            2'b00: SrcA_tmp = RD1E;
            2'b01: SrcA_tmp = ResultW;
            2'b10: SrcA_tmp = ALUResultM;
        endcase
        //RD2
        case (ForwardBE)
            2'b00: SrcB_tmp = RD2E;
            2'b01: SrcB_tmp = ResultW;
            2'b10: SrcB_tmp = ALUResultM;
        endcase

        //next set of Mux
        case(ALUSrcAE)
            2'b00, 2'b10: Src_A = SrcA_tmp;
            2'b01: Src_A = 32'b0;
            2'b11: Src_A = PCE;
        endcase

        case(ALUSrcBE)
            2'b00, 2'b10: Src_B = SrcB_tmp;
            2'b01: Src_B = 32'b4;
            2'b11: Src_B = ExtImmE;
        endcase
    end

    assign WriteDataE = SrcB_tmp;
    assign RD1FwdE = SrcA_tmp;

    wire RegWriteM;
    wire MemtoRegM;
    wire MemWriteM;
    wire Flush;
    wire [31:0] ALUResultM;
    wire [31:0] WriteDataM;
    wire [4:0] rdM;

    MRegister Mregister1 (
        CLK,
        FlushM,
        RegWriteE,
        MemtoRegE, 
        MemWriteE,
        EREGResult,
        WriteDataE,
        rdE,
        RegWriteM, 
        MemtoRegM, 
        MemWriteM,
        ALUResultM, 
        WriteDataM,
        rdM
    );

    wire [31:0] ReadDataM;
    wire [31:0] ReadDataW;
    wire RegWriteW;
    wire MemtoRegW;
    wire [31:0] ALUResultW;
    wire [4:0] rdW;
    wire [31:0] EREGResult;

    assign WriteData = ForwardM ? ResultW : WriteDataM;
    assign EREGResult = (ALUControlE == 4'b1111) ? MCycle_res : ALUResultE; //MCYcle or ALU
    assign WD = ResultW;

    WRegister  WRegister1(
        CLK,
        RegWriteM, 
        MemtoRegM,
        ReadDataM,
        ALUResultM,
        rdM,
        RegWriteW, 
        MemtoRegW,
        ReadDataW,
        ALUResultW,
        rdW
    );

    assign ResultW = MemtoRegW ? ReadDataW : ALUResultW;

    wire StallF;
    wire Forward1D, Forward2D;
    wire [1:0] ForwardAE, ForwardBE;
    wire ForwardM;
    wire UsesRs1D, UsesRs2D;

    //ADD LOGIC TO STALL F and D when Mycyle Busy
    wire MCYCLESTALL;

    reg [4:0] rs1E, rs2E;
    reg [4:0] rs2M;

    always @(posedge CLK) begin
        if (FlushE) begin
            rs1E       <= 5'd0;
            rs2E       <= 5'd0;
            MCycleOpE  <= 2'b00;
        end
        else if (!StallE) begin
            rs1E       <= rs1D;
            rs2E       <= rs2D;
            MCycleOpE  <= MCycleOpD;
        end

        if (FlushM)
            rs2M <= 5'd0;
        else
            rs2M <= rs2E;
    end

    assign UsesRs1D =
        (Opcode == 7'b0110011) ||  // Register ALU, including multiply/divide
        (Opcode == 7'b0010011) ||  // Immediate ALU
        (Opcode == 7'b0000011) ||  // Loads
        (Opcode == 7'b0100011) ||  // Stores: rs1 is the address base
        (Opcode == 7'b1100011) ||  // Conditional branches
        (Opcode == 7'b1100111);    // JALR

    assign UsesRs2D =
        (Opcode == 7'b0110011) ||  // Register ALU, including multiply/divide
        (Opcode == 7'b1100011);    // Conditional branches

    HazardUnit HazardUnit1 (
        rs1D, 
        rs2D, 
        rs1E,
        rs2E,
        rdE,
        rs2M,
        rdM,
        rdW,
        MemtoRegE,
        PCSrcE,
        RegWriteM,
        MemWriteM,
        RegWriteW,
        MemtoRegW,
        UsesRs1D,
        UsesRs2D,
        MCYCLESTALL,
        StallF,
        StallD,
        StallE,
        FlushD,
        FlushE,
        FlushM,
        Forward1D,
        Forward2D,
        ForwardBE,
        ForwardAE,
        ForwardM
    );

    // multicycle signals
    wire Start;
    wire [1:0] MCycleOpD
    reg [1:0] MCycleOpE;
    wire [31:0] Operand1;
    wire [31:0] Operand2;
    wire [31:0] Result1;
    wire [31:0] Result2;
    assign Operand1 = SrcA_tmp; 
    assign Operand2 = SrcB_tmp;
    always @(*) begin
        if (func3E == 3'h0 || func3E == 3'h4 || func3E == 3'h5) //double check
            MCycle_res = Result1;  // lsw or quotient

        else MCycle_res = Result2;  // hsw / remainder
    end

    wire IsMCycleE;
    reg MCycleStarted;

    assign IsMCycleE = (ALUControlE == 4'b1111);

    // Issue Start only once for the instruction held in E.
    assign Start = IsMCycleE && !MCycleStarted && !RESET;

    // Stall on the launch cycle and while the unit is busy.
    assign MCYCLESTALL = IsMCycleE && (!MCycleStarted || Busy);

    always @(posedge CLK) begin
        if (RESET || FlushE)
            MCycleStarted <= 1'b0;
        else if (Start)
            MCycleStarted <= 1'b1;
        else if (!StallE)
            MCycleStarted <= 1'b0;
    end
    
    MCycle MCycle1 (
        CLK,
        RESET,
        Start,
        MCycleOpE,
        Operand1,
        Operand2,
        Result1,
        Result2,
        Busy
    );

    RegFile RegFile1 (
        CLK,
        WE,
        rs1D,
        rs2D,
        rdW,
        WD,
        RD1D,
        RD2D
    );

    Extend Extend1 (
        ImmSrc,
        InstrImm,
        ExtImmD
    );

    // Decoder signals
    wire [6:0] Opcode;
    wire [6:0] Funct7;
    wire [4:0] rs1D, rs2D;

    assign func3D =   InstrD[14:12];
    assign Opcode =   InstrD[6:0];
    assign Funct7 =   InstrD[31:25];
    assign rs1D =     InstrD[19:15];
    assign rs2D =     InstrD[24:20];
    assign rdD  =     InstrD[11:7];
    assign InstrImm = InstrD[31:7];

    Decoder Decoder1 (
        Opcode,
        func3D,
        Funct7,
        PCSD,
        RegWriteD,
        MemWriteD,
        MemtoRegD,
        ALUSrcAD,
        ALUSrcBD,
        ImmSrc,
        ALUControlD,
        MCycleOpD
    );

    // PC_Logic signals
    wire [ 2:0] ALUFlags;
    wire [1:0] PCSrcE;

    PC_Logic PC_Logic1 (
        PCSE,
        func3E,
        ALUFlags,
        PCSrcE
    );

    ALU ALU1 (
        Src_A,
        Src_B,
        ALUControlE,
        func3E,
        ALUResultE,
        ALUFlags
    );

    // ProgramCounter signals
    wire        WE_PC;
    reg  [31:0] PC_IN;
    wire        Busy;
    assign WE_PC = !StallF;
    wire [31:0] RD1FwdE; //TODO

    always @(*) begin
        case (PCSrcE)
            2'b00:   PC_IN = PCF + 32'd4;  //non-control
            2'b01:   PC_IN = PCE + ExtImmE;  //jal
            2'b11:   PC_IN = (RD1FwdE + ExtImmE) & ~32'd1;  //jalr
            default: PC_IN = PCF + 32'd4;  //default case
        endcase
    end

    ProgramCounter #(
        .PC_INIT(PC_INIT)
    ) ProgramCounter1 (
        CLK,
        RESET,
        WE_PC,
        PC_IN,
        PCF
    );
endmodule
